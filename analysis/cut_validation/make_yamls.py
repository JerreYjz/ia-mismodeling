#!/usr/bin/env python3
"""Write chains 2 to 4 of the cut validation from NLA_on_flam_k0p2.yaml.

Only the lines marked "VARIES" in the template change: the dataset, IA_model,
the IA parameters (free TATT terms, ref at the K0 = 0.2 FLAMINGO best fit of
each model) and the output path.

    python make_yamls.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = "NLA_on_flam_k0p2"

NLA_IA = """\
  roman_A1_1: {prior: {min: -5, max: 5}, ref: {dist: norm, loc: 3.486, scale: 0.1}, proposal: 0.1, latex: 'A_1'}
  roman_A1_2: {prior: {min: -5, max: 5}, ref: {dist: norm, loc: 0.700, scale: 0.1}, proposal: 0.1, latex: '\\eta_1'}
  roman_A2_1:  {value: 0.0, latex: 'A_2'}
  roman_A2_2:  {value: 0.0, latex: '\\eta_2'}
  roman_BTA_1: {value: 0.0, latex: 'b_\\mathrm{TA}'}
"""
TATT_IA = """\
  roman_A1_1:  {prior: {min: -5, max: 5}, ref: {dist: norm, loc: 3.424,  scale: 0.1}, proposal: 0.1, latex: 'A_1'}
  roman_A1_2:  {prior: {min: -5, max: 5}, ref: {dist: norm, loc: 0.740,  scale: 0.1}, proposal: 0.1, latex: '\\eta_1'}
  roman_A2_1:  {prior: {min: -5, max: 5}, ref: {dist: norm, loc: -1.317, scale: 0.3}, proposal: 0.3, latex: 'A_2'}
  roman_A2_2:  {prior: {min: -5, max: 5}, ref: {dist: norm, loc: -3.541, scale: 0.5}, proposal: 0.5, latex: '\\eta_2'}
  roman_BTA_1: {prior: {min: 0, max: 2},  ref: {dist: norm, loc: 0.601,  scale: 0.1}, proposal: 0.1, latex: 'b_\\mathrm{TA}'}
"""
NLA_BLOCK = "            roman_A1_1, roman_A1_2]]\n"
TATT_BLOCK = "            roman_A1_1, roman_A1_2, roman_A2_1, roman_A2_2, roman_BTA_1]]\n"

CHAINS = {  # name: (model, dataset)
    "TATT_on_flam_k0p2": ("TATT", "cutval_k0p2_flam.dataset"),
    "NLA_on_nla_k0p2":   ("NLA",  "cutval_k0p2_nla.dataset"),
    "TATT_on_tatt_k0p2": ("TATT", "cutval_k0p2_tatt.dataset"),
}


def sub(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


def main():
    base = open(os.path.join(HERE, BASE + ".yaml")).read()
    for name, (model, dataset) in CHAINS.items():
        t = sub(base, "data_file: cutval_k0p2_flam.dataset", f"data_file: {dataset}")
        t = sub(t, f"chains/cutval/{BASE}", f"chains/cutval/{name}")
        if model == "TATT":
            t = sub(t, "IA_model: 0  ", "IA_model: 1  ")
            t = sub(t, NLA_IA, TATT_IA)
            t = sub(t, NLA_BLOCK, TATT_BLOCK)
        lines = t.splitlines(keepends=True)
        k = next(i for i, l in enumerate(lines) if not l.startswith("#"))
        head = (f"# Cut validation: {name} ({model} fitted to {dataset}).\n"
                f"# Generated by make_yamls.py from {BASE}.yaml; see its header.\n")
        open(os.path.join(HERE, name + ".yaml"), "w").write(head + "".join(lines[k:]))
        print("wrote", name + ".yaml")


if __name__ == "__main__":
    main()
